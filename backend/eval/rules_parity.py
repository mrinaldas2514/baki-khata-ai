"""Write the rule-based parser's answers for the browser port to match. Run from backend/:

    python -m eval.rules_parity

The app parses offline with a TypeScript copy of the rules (frontend/src/offline/rules.ts).
This writes frontend/src/offline/rulesParity.json: for every evaluation sentence and a set of
edge cases, the normalized text and the Python parser's answer. The frontend tests check the
TypeScript port gives exactly the same, and tests/test_rules_parity.py checks the file is up
to date with the Python rules.
"""

import json
from pathlib import Path

from app.llm.rule_based import parse_text
from app.services.number_words import normalize_numbers
from eval.dataset import load_eval_set

OUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "offline" / "rulesParity.json"

# Beyond the evaluation set: number words, joined words, edge cases of both modules.
EXTRA = [
    "salma apa pach sho taka baki", "dedh hajar dilo", "arai sho taka", "sare tin sho",
    "poune dui hajar", "ek hajar pach sho ponchash taka", "dui hajar taka nilo",
    "hajar taka dilo", "bish taka", "pachsho baki", "1.5 hajar", "2 hajar", "5 lakh",
    "sowa sho taka baki", "shoa hajar", "sowa tin sho taka", "sowa dui hajar",
    "সোয়া শো টাকা", "দেড় হাজার টাকার চাল", "পাঁচশো টাকা বাকি", "সাড়ে তিন শো",
    "five hundred taka", "1,25,000 taka", "500 so", "tin kg alu", "met at the shop",
    "sare", "sowa taka", "poune", "sare tin", "দেড়শো টাকা",
    "Rahim Uddin 500 taka dilo", "aj jasim 300 baki", "rahim 300 500 baki",
    "rahim 2 kg chal 120 taka", "200 taka dilo", "rahim 0 taka baki", "Mr. Hasan ৳ 500",
    "rahim ৳500 baki", "tk 300 rahim dilo", "rahim bhai 2kg chal 120tk baki, karim 50 dilo",
    "a 1 b 2 c 3 d 4 e 5 f 6 g 7 h 8 i 9 j 10 k 11",
    "rahim 10 baki, karim 20 baki, salma 30 baki, rina 40 baki, jasim 50 baki, tanvir 60 baki, "
    "kamal 70 baki, monir 80 baki, nasir 90 baki, sumi 100 baki, babu 110 baki",
    "মিজান কাকা ৩৫০ টাকার চিনি আর আটা নিল", "rahim " + "chal " * 60 + "500 baki",
    "", "   ", ",,,", "taka", "rahim", "RAHIM BHAI 500 TAKA BAKI",
]  # fmt: skip


def cases() -> list[dict]:
    texts = [s.text for s in load_eval_set()] + EXTRA
    return [
        {"text": t, "normalized": normalize_numbers(t), "parsed": parse_text(t)}
        for t in dict.fromkeys(texts)
    ]


def render() -> str:
    data = {
        "description": "Generated by `python -m eval.rules_parity` (backend/eval/rules_parity.py): "
        "the Python rule-based parser's answers, which frontend/src/offline/rules.ts must match.",
        "cases": cases(),
    }
    return json.dumps(data, ensure_ascii=False, indent=1) + "\n"


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"Wrote {len(cases())} cases to {OUT}")
